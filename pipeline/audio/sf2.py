"""Offline SoundFont renderer: libfluidsynth through ctypes, float output, sample-accurate events.

Runs on the Spark (CPU). FluidSynth 2.6.2 is built in user space (pipeline/audio/LICENSES.md, scripts/spark_fluidsynth.sh)
into ~/studio/opt/fluidsynth; the SoundFont lives in ~/studio/models/soundfonts/. Only SoundFonts whose licence was
checked and recorded in config.SOUNDFONTS (by sha256) load: that is the Content ID guarantee for the scored music
(every note is generated by pipeline/audio/score.py, every sample comes from a licence-cleared bank).

  r = Renderer()                                   # loads the default bank once
  audio = r.render(events, seconds, programs={0: (0, 49), 9: (128, 48)})
  events: [(t_seconds, "on", chan, key, vel) | (t, "off", chan, key) | (t, "cc", chan, num, val) | (t, "bend", chan, v)]
  returns float32 (n, 2) at config.SR, dry (FluidSynth reverb/chorus off: pipeline/audio/score.py adds its own).
"""
from __future__ import annotations

import ctypes
import functools
import hashlib
import os

import numpy as np

from .config import SOUNDFONTS, SR

HOME = os.path.expanduser("~")
LIB_CANDIDATES = [os.environ.get("STUDIO_FLUIDSYNTH_LIB", ""),
                  os.path.join(HOME, "studio", "opt", "fluidsynth", "lib", "libfluidsynth.so.3"),
                  "libfluidsynth.so.3", "libfluidsynth.so"]
SF_DIR = os.environ.get("STUDIO_SOUNDFONTS", os.path.join(HOME, "studio", "models", "soundfonts"))
BLOCK = 64  # samples rendered between event checks (events are applied at exact sample offsets anyway)


class SoundFontError(RuntimeError):
    pass


@functools.lru_cache(maxsize=None)
def _lib():
    for p in LIB_CANDIDATES:
        if not p:
            continue
        try:
            lib = ctypes.CDLL(p)
            break
        except OSError:
            continue
    else:
        raise SoundFontError("libfluidsynth not found (build it with scripts/spark_fluidsynth.sh or set STUDIO_FLUIDSYNTH_LIB)")
    vp, ci, cd, cs = ctypes.c_void_p, ctypes.c_int, ctypes.c_double, ctypes.c_char_p
    sig = {
        "new_fluid_settings": ([], vp), "delete_fluid_settings": ([vp], None),
        "fluid_settings_setnum": ([vp, cs, cd], ci), "fluid_settings_setint": ([vp, cs, ci], ci),
        "fluid_settings_setstr": ([vp, cs, cs], ci),
        "new_fluid_synth": ([vp], vp), "delete_fluid_synth": ([vp], None),
        "fluid_synth_sfload": ([vp, cs, ci], ci),
        "fluid_synth_program_select": ([vp, ci, ci, ci, ci], ci),
        "fluid_synth_noteon": ([vp, ci, ci, ci], ci), "fluid_synth_noteoff": ([vp, ci, ci], ci),
        "fluid_synth_cc": ([vp, ci, ci, ci], ci), "fluid_synth_pitch_bend": ([vp, ci, ci], ci),
        "fluid_synth_set_interp_method": ([vp, ci, ci], ci),
        "fluid_synth_write_float": ([vp, ci, vp, ci, ci, vp, ci, ci], ci),
    }
    for name, (args, res) in sig.items():
        f = getattr(lib, name)
        f.argtypes, f.restype = args, res
    return lib


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


@functools.lru_cache(maxsize=None)
def soundfont(name: str | None = None) -> dict:
    """The licence-cleared bank: {"name", "path", "sha256", "licence", "source"}; refuses unknown files."""
    name = name or os.environ.get("STUDIO_SOUNDFONT") or next(iter(SOUNDFONTS))
    if name not in SOUNDFONTS:
        raise SoundFontError(f"SoundFont {name!r} is not licence-cleared (config.SOUNDFONTS: {list(SOUNDFONTS)})")
    meta = SOUNDFONTS[name]
    path = os.path.join(SF_DIR, meta["file"])
    if not os.path.exists(path):
        raise SoundFontError(f"{path} missing (download per pipeline/audio/LICENSES.md)")
    digest = sha256(path)
    if digest != meta["sha256"]:
        raise SoundFontError(f"{path} sha256 {digest[:12]} does not match the licence record {meta['sha256'][:12]}")
    return {"name": name, "path": path, "sha256": digest, "licence": meta["licence"], "source": meta["source"]}


def available() -> tuple[bool, str]:
    try:
        _lib()
        soundfont()
        return True, ""
    except SoundFontError as e:
        return False, str(e)


class Renderer:
    def __init__(self, sf_name: str | None = None, gain: float = 0.6):
        self.sf = soundfont(sf_name)
        self.gain = gain

    def render(self, events: list[tuple], seconds: float, programs: dict[int, tuple[int, int]],
               tail: float = 3.0) -> np.ndarray:
        lib = _lib()
        st = lib.new_fluid_settings()
        lib.fluid_settings_setnum(st, b"synth.sample-rate", float(SR))
        lib.fluid_settings_setint(st, b"synth.reverb.active", 0)
        lib.fluid_settings_setint(st, b"synth.chorus.active", 0)
        lib.fluid_settings_setnum(st, b"synth.gain", float(self.gain))
        lib.fluid_settings_setint(st, b"synth.polyphony", 512)
        lib.fluid_settings_setint(st, b"synth.cpu-cores", 1)
        syn = lib.new_fluid_synth(st)
        try:
            sfid = lib.fluid_synth_sfload(syn, self.sf["path"].encode(), 1)
            if sfid < 0:
                raise SoundFontError(f"fluidsynth could not load {self.sf['path']}")
            lib.fluid_synth_set_interp_method(syn, -1, 7)  # 7th-order interpolation (highest quality)
            for ch, (bank, prog) in programs.items():
                lib.fluid_synth_program_select(syn, ch, sfid, bank, prog)
            n = int((seconds + tail) * SR)
            out = np.zeros((2, n), np.float32)
            evs = sorted(events, key=lambda e: (e[0], 0 if e[1] in ("off", "cc", "bend") else 1))
            pos, k = 0, 0
            ptr_l = out[0].ctypes.data
            ptr_r = out[1].ctypes.data
            while pos < n:
                while k < len(evs) and int(round(evs[k][0] * SR)) <= pos:
                    e = evs[k]
                    if e[1] == "on":
                        lib.fluid_synth_noteon(syn, e[2], int(e[3]), max(1, min(127, int(e[4]))))
                    elif e[1] == "off":
                        lib.fluid_synth_noteoff(syn, e[2], int(e[3]))
                    elif e[1] == "cc":
                        lib.fluid_synth_cc(syn, e[2], int(e[3]), max(0, min(127, int(e[4]))))
                    elif e[1] == "bend":
                        lib.fluid_synth_pitch_bend(syn, e[2], int(e[3]))
                    k += 1
                nxt = int(round(evs[k][0] * SR)) if k < len(evs) else n
                m = max(1, min(n - pos, nxt - pos if nxt > pos else BLOCK))
                lib.fluid_synth_write_float(syn, m, ptr_l, pos, 1, ptr_r, pos, 1)
                pos += m
            return out.T.copy()
        finally:
            lib.delete_fluid_synth(syn)
            lib.delete_fluid_settings(st)
